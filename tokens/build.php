<?php
/**
 * Compile every preset in tokens/presets/ into:
 *   dist/tokens/presets.css          all presets, scoped as [data-preset="id"]
 *   dist/tokens/<id>.css             one preset on :root (what a single site ships)
 *   dist/tokens/fonts.json           Google Fonts URL per preset
 *   dist/wp/theme-json/<id>.json     theme.json for the WP custom theme
 * and print a WCAG contrast report. Exits 1 if any preset fails.
 *
 * Usage: php tokens/build.php
 */

$root = dirname(__DIR__);
require "$root/lib/tokens.php";

$presets = sx_all_presets($root);
@mkdir("$root/dist/tokens", 0777, true);
@mkdir("$root/dist/wp/theme-json", 0777, true);

$all = "/* Generated by tokens/build.php. Do not edit. */\n";
$fonts = [];
$failed = 0;

foreach ($presets as $id => $p) {
    $vars = sx_token_vars($p);
    $all .= sx_vars_to_css($vars, "[data-preset=\"$id\"]");
    file_put_contents("$root/dist/tokens/$id.css", "/* $p[name] - generated */\n" . sx_vars_to_css($vars, ':root'));
    file_put_contents("$root/dist/wp/theme-json/$id.json", json_encode(sx_theme_json($p), JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES));
    $fonts[$id] = sx_google_fonts_url([$p]);

    $report = sx_contrast_report($p);
    $bad = array_filter($report, fn($r) => !$r['pass']);
    $failed += count($bad);
    $summary = implode('  ', array_map(fn($r) => ($r['pass'] ? '' : '!') . $r['ratio'], $report));
    printf("%-18s %s %s\n", $id, $bad ? 'FAIL' : 'ok  ', $summary);
    foreach ($bad as $r) {
        printf("    %s: %.2f (needs %.1f)\n", $r['pair'], $r['ratio'], $r['min']);
    }
}

file_put_contents("$root/dist/tokens/presets.css", $all);
file_put_contents("$root/dist/tokens/fonts.json", json_encode(['all' => sx_google_fonts_url($presets)] + $fonts, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES));

echo "\nColumns: text/bg, muted/bg, text/surface, muted/surface, accent button, hero button\n";
echo count($presets) . " presets compiled to dist/tokens and dist/wp/theme-json\n";
exit($failed ? 1 : 0);
